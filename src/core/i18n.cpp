void set_lang(Lang l) { s_lang = l; }
Lang lang() { return s_lang; }

Lang parse(const std::string &code)
{
    if (code.size() >= 2 && std::tolower((unsigned char)code[0]) == 'f' && std::tolower((unsigned char)code[1]) == 'r')
        return Lang::French;
    return Lang::English;
}

const char *tr(S key)
{
    if (key < 0 || key >= Count)
        return "";
    const char *t = s_lang == Lang::French ? kTable[key].fr : kTable[key].en;
    return t ? t : "";
}

